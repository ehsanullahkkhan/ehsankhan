# 4. Discover image files and labels
IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}

records = []
for file in DATASET_ROOT.rglob("*"):
    if file.is_file() and file.suffix.lower() in IMAGE_EXTS:
        rel = file.relative_to(DATASET_ROOT)
        label = rel.parts[0] if len(rel.parts) >= 2 else file.parent.name
        records.append((str(file), label))

df = pd.DataFrame(records, columns=["filepath", "label"])

if df.empty:
    raise RuntimeError("No images found. Check the printed dataset directory.")

df = df.drop_duplicates("filepath").reset_index(drop=True)

print("Total images:", len(df))
print(df["label"].value_counts())
display(df.head())

# 5. Validate images and remove exact duplicates
valid = []
seen = set()

for row in df.itertuples(index=False):
    fp = Path(row.filepath)
    try:
        with Image.open(fp) as im:
            im.verify()
        digest = hashlib.sha256(fp.read_bytes()).hexdigest()
        if digest in seen:
            continue
        seen.add(digest)
        valid.append((row.filepath, row.label))
    except Exception:
        pass

df = pd.DataFrame(valid, columns=["filepath", "label"]).reset_index(drop=True)

print("Valid unique images:", len(df))
print("\nClass distribution:")
print(df["label"].value_counts())

# 6. Stratified train/validation/test split
class_names = sorted(df["label"].unique().tolist())
NUM_CLASSES = len(class_names)
if NUM_CLASSES < 2: raise RuntimeError(f"Expected at least 2 classes, found: {class_names}")
class_counts = df["label"].value_counts()
if (class_counts < 3).any(): raise RuntimeError(f"Every class needs at least 3 images. Small classes: {class_counts[class_counts < 3].to_dict()}")
train_df, temp_df = train_test_split(df, test_size=0.30, stratify=df["label"], random_state=SEED)
val_df, test_df = train_test_split(temp_df, test_size=0.50, stratify=temp_df["label"], random_state=SEED)
class_indices = {name: i for i, name in enumerate(class_names)}
print("Classes:", class_names); print("Train:", len(train_df)); print("Validation:", len(val_df)); print("Test:", len(test_df))

# 7. Class-balanced weights
y_train = train_df["label"].map(class_indices).to_numpy()
weights = compute_class_weight(
    class_weight="balanced",
    classes=np.arange(NUM_CLASSES),
    y=y_train
)
class_weight = {i: float(w) for i, w in enumerate(weights)}

print("Class weights:", class_weight)

"""## 4. Data pipeline and augmentation"""

# 8. tf.data pipeline
IMG_SIZE = (224, 224)
BATCH_SIZE = 16
AUTOTUNE = tf.data.AUTOTUNE

def load_image(path, label):
    image = tf.io.read_file(path)
    image = tf.image.decode_image(image, channels=3, expand_animations=False)
    image.set_shape([None, None, 3])
    image = tf.image.resize(image, IMG_SIZE, antialias=True)
    return tf.cast(image, tf.float32), label

def make_dataset(frame, training=False):
    paths = frame["filepath"].to_numpy(dtype=str)
    labels = frame["label"].map(class_indices).to_numpy(dtype=np.int32)
    ds = tf.data.Dataset.from_tensor_slices((paths, labels))
    if training: ds = ds.shuffle(len(frame), seed=SEED, reshuffle_each_iteration=True)
    return ds.map(load_image, num_parallel_calls=AUTOTUNE).batch(BATCH_SIZE).prefetch(AUTOTUNE)

train_ds = make_dataset(train_df, training=True)
val_ds = make_dataset(val_df)
test_ds = make_dataset(test_df)

def make_augmentation():
    return keras.Sequential([
        layers.RandomFlip("horizontal"), layers.RandomRotation(0.08), layers.RandomZoom(0.12),
        layers.RandomTranslation(0.05, 0.05), layers.RandomContrast(0.10)
    ], name="augmentation")

"""## 5. Hyperparameter tuning"""

# 9. Robust EfficientNetV2B0 hyperparameter tuning
# A fresh augmentation layer and backbone are created for every tuner trial.
def build_tunable_model(hp):
    tf.keras.backend.clear_session()
    base = keras.applications.EfficientNetV2B0(include_top=False, weights="imagenet", input_shape=IMG_SIZE+(3,), include_preprocessing=True)
    base.trainable = False
    inputs = keras.Input(shape=IMG_SIZE+(3,), name="image")
    x = make_augmentation()(inputs)
    x = base(x, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(hp.Float("dropout", 0.2, 0.5, step=0.1))(x)
    x = layers.Dense(hp.Choice("dense_units", [128, 256]), activation="relu")(x)
    x = layers.Dropout(hp.Float("dropout2", 0.1, 0.3, step=0.1))(x)
    outputs = layers.Dense(NUM_CLASSES, activation="softmax", dtype="float32")(x)
    model = keras.Model(inputs, outputs)
    model.compile(optimizer=keras.optimizers.AdamW(
        learning_rate=hp.Float("learning_rate", 1e-4, 2e-3, sampling="log"),
        weight_decay=hp.Float("weight_decay", 1e-6, 1e-4, sampling="log")),
        loss=keras.losses.SparseCategoricalCrossentropy(label_smoothing=0.05),
        metrics=[keras.metrics.SparseCategoricalAccuracy(name="accuracy")])
    return model

tuner = kt.RandomSearch(hypermodel=build_tunable_model, objective=kt.Objective("val_accuracy", direction="max"),
    max_trials=5, executions_per_trial=1, overwrite=True, directory="/content/keras_tuner", project_name="skin_classifier")
print("Starting hyperparameter tuning...")
tuner.search(train_ds, validation_data=val_ds, epochs=6, class_weight=class_weight,
    callbacks=[keras.callbacks.EarlyStopping(monitor="val_accuracy", patience=2, restore_best_weights=True)], verbose=1)
best_hp = tuner.get_best_hyperparameters(num_trials=1)[0]
print("Best hyperparameters:")
for k, v in best_hp.values.items(): print(f"  {k}: {v}")

"""## 6. Training and fine-tuning"""

# 10. Train the best hyperparameter configuration
tf.keras.backend.clear_session()
model = tuner.hypermodel.build(best_hp)
callbacks = [
    keras.callbacks.EarlyStopping(monitor="val_accuracy", patience=4, restore_best_weights=True),
    keras.callbacks.ReduceLROnPlateau(monitor="val_loss", factor=0.3, patience=2, min_lr=1e-7),
    keras.callbacks.ModelCheckpoint("/content/best_head.keras", monitor="val_accuracy", save_best_only=True)
]
history = model.fit(train_ds, validation_data=val_ds, epochs=15, class_weight=class_weight, callbacks=callbacks, verbose=1)
if Path("/content/best_head.keras").exists(): model = keras.models.load_model("/content/best_head.keras")
print("Best validation accuracy:", float(max(history.history["val_accuracy"])))

# 11. Fine-tune the last 30% of the pretrained backbone
base_model = next((layer for layer in model.layers if isinstance(layer, keras.Model) and "efficientnet" in layer.name.lower()), None)
if base_model is None: raise RuntimeError(f"EfficientNet backbone not found. Nested models: {[x.name for x in model.layers if isinstance(x, keras.Model)]}")
base_model.trainable = True
start = int(len(base_model.layers) * 0.70)
for i, layer in enumerate(base_model.layers):
    layer.trainable = i >= start
    if isinstance(layer, layers.BatchNormalization): layer.trainable = False
base_lr = float(best_hp.get("learning_rate")); weight_decay = float(best_hp.get("weight_decay"))
model.compile(optimizer=keras.optimizers.AdamW(learning_rate=base_lr*0.1, weight_decay=weight_decay),
    loss=keras.losses.SparseCategoricalCrossentropy(label_smoothing=0.03),
    metrics=[keras.metrics.SparseCategoricalAccuracy(name="accuracy")])
callbacks_ft = [
    keras.callbacks.EarlyStopping(monitor="val_accuracy", patience=5, restore_best_weights=True),
    keras.callbacks.ReduceLROnPlateau(monitor="val_loss", factor=0.3, patience=2, min_lr=1e-8),
    keras.callbacks.ModelCheckpoint("/content/best_finetuned.keras", monitor="val_accuracy", save_best_only=True)
]
history_ft = model.fit(train_ds, validation_data=val_ds, epochs=20, class_weight=class_weight, callbacks=callbacks_ft, verbose=1)
if Path("/content/best_finetuned.keras").exists(): model = keras.models.load_model("/content/best_finetuned.keras")

