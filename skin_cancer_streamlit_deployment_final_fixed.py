# 13. Horizontal-flip test-time augmentation
def make_flip_dataset(frame):
    paths = frame["filepath"].to_numpy(dtype=str)
    labels = frame["label"].map(class_indices).to_numpy(dtype=np.int32)
    ds = tf.data.Dataset.from_tensor_slices((paths, labels))
    def loader(path, label):
        image = tf.io.read_file(path)
        image = tf.image.decode_image(image, channels=3, expand_animations=False)
        image.set_shape([None, None, 3])
        image = tf.image.resize(image, IMG_SIZE, antialias=True)
        image = tf.image.flip_left_right(tf.cast(image, tf.float32))
        return image, label
    return ds.map(loader, num_parallel_calls=AUTOTUNE).batch(BATCH_SIZE).prefetch(AUTOTUNE)
flip_ds = make_flip_dataset(test_df)
flip_probs = model.predict(flip_ds, verbose=0)
tta_probs = (test_probs + flip_probs) / 2.0
tta_preds = np.argmax(tta_probs, axis=1)
print("TTA accuracy:", accuracy_score(test_true, tta_preds))
print("TTA balanced accuracy:", balanced_accuracy_score(test_true, tta_preds))
print("TTA macro F1:", f1_score(test_true, tta_preds, average="macro"))

