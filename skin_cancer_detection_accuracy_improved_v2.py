def train_one_model(model_name, hp=None):
    hp = hp or TUNED_HP

    print("\n" + "=" * 80)
    print("TRAINING:", model_name)
    print("=" * 80)

    dropout = hp["dropout"] if model_name == "EfficientNetV2B0" else 0.35
    dense_units = hp["dense_units"] if model_name == "EfficientNetV2B0" else 256
    head_lr = hp["learning_rate"] if model_name == "EfficientNetV2B0" else 3e-4
    wd = hp["weight_decay"] if model_name == "EfficientNetV2B0" else 1e-5

    model, base = build_transfer_model(
        model_name, dropout=dropout,
        dense_units=dense_units, l2_strength=wd
    )

    # Stage 1: classifier head.
    compile_model(model, lr=head_lr, weight_decay=wd)
    history_head = model.fit(
        train_ds, validation_data=val_ds,
        epochs=HEAD_EPOCHS,
        class_weight=class_weights,
        callbacks=make_callbacks(model_name, "head"),
        verbose=1
    )

    # Stage 2: fine-tune final 25% of the backbone.
    base.trainable = True
    fine_tune_from = int(len(base.layers) * (1.0 - FINE_TUNE_FRACTION))
    for layer in base.layers[:fine_tune_from]:
        layer.trainable = False

    # Freeze BatchNorm for small-data stability.
    for layer in base.layers:
        if isinstance(layer, layers.BatchNormalization):
            layer.trainable = False

    compile_model(model, lr=1e-5, weight_decay=wd)

    history_ft = model.fit(
        train_ds, validation_data=val_ds,
        initial_epoch=len(history_head.history["loss"]),
        epochs=HEAD_EPOCHS + FINE_TUNE_EPOCHS,
        class_weight=class_weights,
        callbacks=make_callbacks(model_name, "finetune"),
        verbose=1
    )

    best_path = MODEL_DIR / f"{model_name}_finetune_best.keras"
    best_model = keras.models.load_model(best_path)
    return best_model, (history_head, history_ft)

