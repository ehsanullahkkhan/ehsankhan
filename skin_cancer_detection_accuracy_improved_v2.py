def get_backbone(model_name):
    if model_name == "EfficientNetV2B0":
        return keras.applications.EfficientNetV2B0(
            include_top=False, weights="imagenet",
            input_shape=(*IMG_SIZE, 3)
        )
    if model_name == "DenseNet121":
        return keras.applications.DenseNet121(
            include_top=False, weights="imagenet",
            input_shape=(*IMG_SIZE, 3)
        )
    if model_name == "ResNet50":
        return keras.applications.ResNet50(
            include_top=False, weights="imagenet",
            input_shape=(*IMG_SIZE, 3)
        )
    raise ValueError(model_name)

def preprocess_for(model_name, x):
    if model_name == "EfficientNetV2B0":
        return x
    if model_name == "DenseNet121":
        return keras.applications.densenet.preprocess_input(x)
    if model_name == "ResNet50":
        return keras.applications.resnet50.preprocess_input(x)
    raise ValueError(model_name)

def build_transfer_model(model_name, dropout=0.35, dense_units=256, l2_strength=1e-5):
    inputs = keras.Input(shape=(*IMG_SIZE, 3), name="image")
    x = data_augmentation(inputs)
    x = preprocess_for(model_name, x)

    base = get_backbone(model_name)
    base.trainable = False

    x = base(x, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dense(
        dense_units, activation="swish",
        kernel_regularizer=keras.regularizers.l2(l2_strength)
    )(x)
    x = layers.Dropout(dropout)(x)
    outputs = layers.Dense(NUM_CLASSES, activation="softmax")(x)

    return keras.Model(inputs, outputs, name=model_name), base

def compile_model(model, lr, weight_decay=1e-5):
    try:
        optimizer = keras.optimizers.AdamW(
            learning_rate=lr, weight_decay=weight_decay
        )
    except Exception:
        optimizer = keras.optimizers.Adam(learning_rate=lr)

    model.compile(
        optimizer=optimizer,
        loss=keras.losses.SparseCategoricalCrossentropy(
            label_smoothing=LABEL_SMOOTHING
        ),
        metrics=[keras.metrics.SparseCategoricalAccuracy(name="accuracy")]
    )

def make_callbacks(model_name, stage, patience=5):
    checkpoint_path = MODEL_DIR / f"{model_name}_{stage}_best.keras"
    return [
        keras.callbacks.ModelCheckpoint(
            checkpoint_path, monitor="val_accuracy",
            save_best_only=True, mode="max", verbose=1
        ),
        keras.callbacks.EarlyStopping(
            monitor="val_accuracy", patience=patience,
            mode="max", restore_best_weights=True, verbose=1
        ),
        keras.callbacks.ReduceLROnPlateau(
            monitor="val_loss", factor=0.3,
            patience=2, min_lr=1e-7, verbose=1
        )
    ]

MODEL_NAMES = ["EfficientNetV2B0", "DenseNet121", "ResNet50"]

def tuner_model_builder(hp):
    dropout = hp.Float("dropout", 0.20, 0.60, step=0.05)
    dense_units = hp.Choice("dense_units", [128, 256, 384, 512])
    lr = hp.Float("learning_rate", 1e-5, 5e-4, sampling="log")
    wd = hp.Float("weight_decay", 1e-7, 1e-4, sampling="log")

    model, _ = build_transfer_model(
        "EfficientNetV2B0",
        dropout=dropout,
        dense_units=dense_units,
        l2_strength=wd
      )
    compile_model(model, lr=lr, weight_decay=wd)
    return model

